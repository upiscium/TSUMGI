"""Optional Control-local, pre-admission PCM WAV input staging.

Receipts and bytes are process-local and expire independently of durable Jobs.
Never use an uploaded URI as a filesystem path or as Worker authorization.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from io import BytesIO
from threading import RLock
import struct
import wave

from ..control.models import JobStatus
from ..control.repository import ConflictError, NotFoundError, RepositoryError
from ..execution import ArtifactRef
from .artifact_spool import ArtifactSpool


_ERROR = "audio input unavailable or unauthorized"


@dataclass
class _Input:
    artifact_id: str
    scope: str
    reference: ArtifactRef
    job_id: str | None = None
    failed_admission: bool = False


def _reference_dict(reference: ArtifactRef) -> dict:
    # This is the entire durable payload addition: metadata, never WAV bytes.
    return {
        "uri": reference.uri,
        "media_type": reference.media_type,
        "digest": reference.digest,
        "size_bytes": reference.size_bytes,
    }


class AudioInputChannel:
    """Serialized pre-admission receipts and current-attempt Worker reads."""

    def __init__(
        self, repository, spool: ArtifactSpool, *, max_bytes: int,
        max_decoded_bytes: int, max_duration_seconds: int = 60,
    ):
        if not isinstance(spool, ArtifactSpool):
            raise TypeError("spool must be ArtifactSpool")
        if (spool._max_total_bytes is None or spool._max_artifacts is None):
            raise ValueError("finite aggregate spool quotas required")
        if (type(max_bytes) is not int or max_bytes < 44
                or max_bytes > spool._max_bytes):
            raise ValueError("invalid audio input byte limit")
        if type(max_decoded_bytes) is not int or max_decoded_bytes < 2:
            raise ValueError("invalid decoded audio byte limit")
        if type(max_duration_seconds) is not int or max_duration_seconds < 1:
            raise ValueError("invalid audio duration limit")
        if not callable(getattr(repository, "_authorize_audio_artifact_attempt", None)):
            raise ValueError("audio Job attempt authority is required")
        self.repository = repository
        self.max_bytes = max_bytes
        self._max_decoded_bytes = max_decoded_bytes
        self._max_duration = max_duration_seconds
        self._spool = spool
        self._lock = RLock()
        self._inputs: dict[str, _Input] = {}

    def _validate_pcm16(self, data: bytes) -> None:
        if (type(data) is not bytes or not 44 <= len(data) <= self.max_bytes
                or data[:4] != b"RIFF" or data[8:12] != b"WAVE"):
            raise ValueError("bounded PCM16 WAV required")
        try:
            with wave.open(BytesIO(data), "rb") as wav:
                channels = wav.getnchannels()
                rate = wav.getframerate()
                frames = wav.getnframes()
                if (wav.getcomptype() != "NONE" or wav.getsampwidth() != 2
                        or channels not in (1, 2) or not 8000 <= rate <= 48000
                        or frames < 1 or frames > rate * self._max_duration
                        or frames * channels * 2 > self._max_decoded_bytes):
                    raise ValueError("unsupported PCM16 WAV format or duration")
                decoded = wav.readframes(frames)
                if len(decoded) != frames * channels * 2:
                    raise ValueError("truncated PCM16 WAV frames")
        except (wave.Error, EOFError, OSError, OverflowError, struct.error) as exc:
            raise ValueError("malformed PCM16 WAV") from exc

    def _reap_expired_locked(self) -> int:
        freed = self._spool.reap_expired()
        for token in tuple(self._inputs):
            if token not in self._spool._records:
                del self._inputs[token]
        return freed

    def _discard_locked(self, pending: _Input) -> bool:
        try:
            self._spool.delete(pending.artifact_id, scope=pending.scope)
        except (OSError, ValueError):
            # Failed cleanup retains charged quota; do not permit rebinding.
            pending.failed_admission = True
            return False
        self._inputs.pop(pending.artifact_id, None)
        return True

    def stage(self, data: bytes) -> ArtifactRef:
        with self._lock:
            self._reap_expired_locked()
            self._validate_pcm16(data)
            # The scope is generated by Control; caller-supplied values never
            # become file names or Spool authorization labels.
            scope = "audio-input-staged"
            receipt = self._spool.stage(data, scope=scope)
            ref = ArtifactRef(
                uri=f"tsumgi-audio-input:{receipt['artifact_id']}",
                media_type="audio/wav",
                digest=f"sha256:{receipt['sha256']}",
                size_bytes=receipt["size"],
            )
            self._inputs[receipt["artifact_id"]] = _Input(
                artifact_id=receipt["artifact_id"], scope=scope, reference=ref,
            )
            return ref

    def abort_unbound(self, artifact_id: str) -> None:
        """Discard an unbound staged input after invalid Job admission JSON."""
        with self._lock:
            pending = self._inputs.get(artifact_id)
            if pending is not None and pending.job_id is None:
                pending.failed_admission = True
                self._discard_locked(pending)

    def admit(self, artifact_id: str, submission):
        """Bind the exact staged input to a durable Job; delete on failure.

        A Control-local lock serializes token consumption and initial binding.
        This is not a PostgreSQL/filesystem atomic commit across crashes.
        """
        with self._lock:
            self._reap_expired_locked()
            pending = self._inputs.get(artifact_id)
            if pending is None or pending.failed_admission:
                raise ConflictError(_ERROR)

            # A committed Job may have succeeded while its HTTP 201 response
            # was lost. Replaying exactly the same keyed request must use the
            # durable repository's idempotency check without rebinding/deleting
            # the input or creating a second Job.
            if pending.job_id is not None:
                if (not submission.idempotency_key
                        or submission.capability != "audio.transcribe"
                        or submission.serving is None
                        or submission.deadline_at is None
                        or "audio_input" in submission.payload):
                    raise ConflictError(_ERROR)
                previous = self.repository.get_job(pending.job_id)
                if previous.idempotency_key != submission.idempotency_key:
                    raise ConflictError(_ERROR)
                replay_payload = dict(submission.payload)
                replay_payload["audio_input"] = _reference_dict(pending.reference)
                replay = self.repository.submit_job(
                    replace(submission, payload=replay_payload)
                )
                if replay.job_id != pending.job_id:
                    raise ConflictError(_ERROR)
                return replay

            try:
                if submission.capability != "audio.transcribe":
                    raise ValueError("staged input requires audio.transcribe")
                if submission.serving is None or submission.deadline_at is None:
                    raise ValueError("staged input requires a serving-bound Job")
                if "audio_input" in submission.payload:
                    raise ValueError("audio_input is assigned by Control")
                # A staged token must still point at valid, unexpired bytes.
                self._spool.read(artifact_id, scope=pending.scope)
                payload = dict(submission.payload)
                payload["audio_input"] = _reference_dict(pending.reference)
                bound = replace(submission, payload=payload)
                job = self.repository.submit_job(bound)
                if (job.capability != "audio.transcribe"
                        or dict(job.payload).get("audio_input") != payload["audio_input"]):
                    raise ConflictError(_ERROR)
            except Exception:
                self._discard_locked(pending)
                raise
            pending.job_id = job.job_id
            return job

    def read_for_worker(
        self, job_id: str, artifact_id: str, *, worker_id: str,
        attempt: int, lease_token: str, runtime_instance_epoch: str,
    ) -> bytes:
        with self._lock:
            self._reap_expired_locked()
            pending = self._inputs.get(artifact_id)
            if (pending is None or pending.failed_admission
                    or pending.job_id != job_id):
                raise NotFoundError(_ERROR)
            self.repository._authorize_audio_artifact_attempt(
                job_id, worker_id=worker_id, attempt=attempt,
                lease_token=lease_token,
                runtime_instance_epoch=runtime_instance_epoch,
            )
            job = self.repository.get_job(job_id)
            if (job.capability != "audio.transcribe"
                    or job.payload.get("audio_input") != _reference_dict(pending.reference)):
                raise ConflictError(_ERROR)
            try:
                data = self._spool.read(artifact_id, scope=pending.scope)
            except ValueError as exc:
                raise NotFoundError(_ERROR) from exc
            # Fencing is not a reusable pre-I/O grant.
            self.repository._authorize_audio_artifact_attempt(
                job_id, worker_id=worker_id, attempt=attempt,
                lease_token=lease_token,
                runtime_instance_epoch=runtime_instance_epoch,
            )
            return data

    def reap(self) -> int:
        """Reclaim expired/unadmitted and durably terminal inputs.

        Retain QUEUED and RUNNING inputs across retries, and on DB outages.
        """
        with self._lock:
            removed = self._reap_expired_locked()
            for token, pending in tuple(self._inputs.items()):
                if pending.failed_admission:
                    abandoned = True
                elif pending.job_id is None:
                    continue  # bounded by the pre-admission Spool TTL
                else:
                    try:
                        job = self.repository.get_job(pending.job_id)
                    except NotFoundError:
                        abandoned = True
                    except RepositoryError:
                        continue
                    else:
                        abandoned = (
                            job.status in (JobStatus.SUCCEEDED, JobStatus.FAILED,
                                           JobStatus.CANCELLED)
                            or job.payload.get("audio_input")
                            != _reference_dict(pending.reference)
                        )
                if abandoned and self._discard_locked(pending):
                    removed += 1
            return removed
